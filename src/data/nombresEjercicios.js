const BASE = /\b(push[- ]?ups?|squats?|dips?|pull[- ]?ups?|chin[- ]?ups?|curls?|crunch(es)?|sit[- ]?ups?|rows?|barbell|dumbbells?|cable|lever|smith|bodyweight|band|kettlebell|exercise|the|with|on|and|of|to|a|an)\b/gi;

export function varianteDe(nombreEn = "") {
  let t = String(nombreEn).replace(/[()]/g, " ");
  PALABRAS.forEach(([r, es]) => (t = t.replace(r, ` ${es} `)));
  t = t.replace(BASE, " ").replace(/\s+/g, " ").trim();
  return t ? t.charAt(0).toLowerCase() + t.slice(1) : "";
}
